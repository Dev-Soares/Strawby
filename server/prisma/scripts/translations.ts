/**
 * Traduz um nome USDA/CNF/LIVS estilo "Rice, brown, long-grain, cooked".
 * Tenta bi-gramas primeiro ("brown sugar", "sweet potato", "top round"),
 * depois tokens simples. Preserva estrutura de vírgulas.
 * Termos desconhecidos permanecem no idioma original.
 */
export function translateName(original: string): string {
  if (!original) return original

  // Tokeniza preservando separadores (vírgulas e espaços como tokens separados)
  const tokens = original.split(/(\s+|,)/)
  const result: string[] = []
  let i = 0

  while (i < tokens.length) {
    const token = tokens[i]
    const trimmed = token.trim()

    if (!trimmed || trimmed === ',') {
      result.push(token)
      i++
      continue
    }

    // Tenta bi-grama: token_atual + espaço + próximo_token
    let matched = false
    if (i + 2 < tokens.length) {
      const sep = tokens[i + 1]
      const nextToken = tokens[i + 2]
      const nextTrimmed = nextToken?.trim()
      // Só tenta bi-grama se o separador for espaço (não vírgula)
      if (sep && /^\s+$/.test(sep) && nextTrimmed && nextTrimmed !== ',') {
        const bigramKey = (trimmed + ' ' + nextTrimmed).toLowerCase()
        const bigramTrans = wordTranslations[bigramKey]
        if (bigramTrans !== undefined) {
          result.push(token.replace(trimmed, bigramTrans))
          result.push('') // substitui o espaço (já incorporado acima)
          result.push('') // consome próximo token
          i += 3
          matched = true
        }
      }
    }

    if (!matched) {
      const key = trimmed.toLowerCase().replace(/[.;:]$/, '')
      const trans = wordTranslations[key]
      if (trans !== undefined) {
        const suffix = trimmed.match(/[.;:]$/)?.[0] ?? ''
        result.push(token.replace(trimmed, trans + suffix))
      } else {
        result.push(token)
      }
      i++
    }
  }

  let final = result.join('').replace(/\s+/g, ' ').replace(/\s+,/g, ',').trim()
  if (final.length > 0) final = final[0].toUpperCase() + final.slice(1)
  return final
}

/**
 * Decide se um nome traduzido tem qualidade boa o bastante.
 * Se >50% das palavras significativas ficaram em EN, retorna false.
 */
export function isTranslationGoodEnough(translated: string, original: string): boolean {
  const origWords = original.toLowerCase().split(/[\s,]+/).filter((w) => w.length > 3)
  if (origWords.length === 0) return true

  const stillEnglish = origWords.filter((w) => wordTranslations[w] === undefined).length
  return stillEnglish / origWords.length < 0.5
}
